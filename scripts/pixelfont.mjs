/** Returns lit pixels of `text` as [{x, y}] in pixel units, plus total width. */
export function layout(text) {
  const pixels = []
  let cx = 0
  for (const ch of text.toUpperCase()) {
    const glyph = G[ch] ?? G[' ']
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') pixels.push({ x: cx + x, y })
    })
    cx += glyph[0].length + 1
  }
  return { pixels, width: Math.max(0, cx - 1) }
}
